  const openedSteps = [...document.querySelectorAll('.project-step')].map(detail => detail.open);
  document.documentElement.lang = {zh: 'zh-CN', en: 'en', fr: 'fr', ja: 'ja'}[language];
  document.title = text.metadata.title;
  document.querySelector('meta[name="description"]').content = text.metadata.description;
  document.querySelectorAll('[data-i18n]').forEach(element => { const value = getPath(text, element.dataset.i18n); if (value !== undefined) element.textContent = value; });
  document.querySelectorAll('[data-i18n-aria]').forEach(element => element.setAttribute('aria-label', getPath(text, element.dataset.i18nAria)));
  document.querySelectorAll('[data-i18n-alt]').forEach(element => element.alt = getPath(text, element.dataset.i18nAlt));
