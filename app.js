  document.querySelector('#project-details').innerHTML = content.project.map(([label, body], index) => `<details class="project-step"${(openedSteps.length ? openedSteps[index] : index === 0) ? ' open' : ''}><summary><span class="step-num">0${index + 1}</span><span>${escapeHtml(label)}</span><span class="step-toggle" aria-hidden="true"></span></summary><p>${escapeHtml(body)}</p></details>`).join('');
  document.querySelector('#education-period').textContent = content.period;
  document.querySelector('#education-status').textContent = content.status;
  document.querySelector('#education-programme').textContent = content.programme;
  document.querySelector('#education-courses').textContent = content.courses;
  document.querySelector('#languages').innerHTML = content.languages.map(([label, body]) => `<div class="language"><h4>${escapeHtml(label)}</h4><p>${escapeHtml(body)}</p></div>`).join('');
